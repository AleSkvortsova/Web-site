@app.post("/api/chat")
def api_chat():
    payload = request.get_json(silent=True) or {}
    question = str(payload.get("message") or payload.get("question") or "").strip()
    history = normalize_chat_history(payload.get("history"))
    debug = payload.get("debug") is True
    if not question:
        return json_response({"error": "Message is required."}, status=400)

    try:
        from rag_core import answer_question

        result = answer_question(question, history=history)
        return json_response(format_chat_response(result, debug=debug))
    except ValueError as exc:
        return json_response({"error": str(exc)}, status=400)
    except RuntimeError as exc:
        return json_response({"error": str(exc)}, status=500)


