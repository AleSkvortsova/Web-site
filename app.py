def json_response(data, status: int = 200):
    return Response(
        json.dumps(data, ensure_ascii=False),
        status=status,
        mimetype="application/json; charset=utf-8",
    )


def format_chat_response(result: dict, debug: bool = False) -> dict:
    if debug:
        return result

    sources = []
    seen = set()
    for source in result.get("sources") or []:
        source_name = source.get("source")
        title = source.get("title")
        key = (source_name, title)
        if key in seen:
            continue
        seen.add(key)
        clean_source = {}
        if source_name:
            clean_source["source"] = source_name
        if title:
            clean_source["title"] = title
        if clean_source:
            sources.append(clean_source)

    return {
        "answer": result.get("answer", ""),
        "sources": sources,
    }


def normalize_chat_history(raw_history, limit: int = 6) -> list[dict[str, str]]:
    if not isinstance(raw_history, list):
        return []

    history: list[dict[str, str]] = []
    for item in raw_history[-limit:]:
        if not isinstance(item, dict):
            continue
        role = item.get("role")
        content = str(item.get("content") or "").strip()
        if role not in {"user", "assistant"} or not content:
            continue
        history.append(
            {
                "role": role,
                "content": content[:1200],
            }
        )
    return history


